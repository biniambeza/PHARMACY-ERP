// Monthly automatic insurance claim batching. Owner: Insurance agent.
//
// For every pharmacy with insurance schemes, builds one DRAFT claim per scheme (autoClaim !== false,
// claimCycle !== 'on_demand'; month edges in INSURANCE_CLAIM_TZ / JOBS_TZ, default Africa/Addis_Ababa)
// from the unclaimed insurance sales of the previous calendar month. Claims are never submitted
// automatically: staff review, refresh and submit them from the Claims tab.
//
// Idempotent: only sales with insurance.claimId = null are picked up (services/insurance.js
// buildClaimForPeriod), so running the job twice for the same month creates nothing the second time.
//
// Scheduled from jobs/index.js (INSURANCE_CLAIM_CRON, default '0 2 1 * *' = 02:00 on the 1st).
// Tests call runInsuranceClaims({ now }) directly.
const mongoose = require('mongoose');
const Pharmacy = require('../models/Pharmacy');
const InsuranceScheme = require('../models/InsuranceScheme');
const svc = require('../services/insurance');
const { audit } = require('../utils/audit');
const { jobsTimeZone, validTimeZone } = require('./lock');

const DEFAULT_INSURANCE_CLAIM_CRON = '0 2 1 * *';

const isTest = () => process.env.NODE_ENV === 'test';
const logError = (...args) => {
  if (!isTest()) console.error('[jobs:insurance-claims]', ...args);
};

// Time zone for the month edges: INSURANCE_CLAIM_TZ, else JOBS_TZ, else Africa/Addis_Ababa
// (the same default as the schedules in jobs/index.js).
const claimTimeZone = () => {
  const tz = (process.env.INSURANCE_CLAIM_TZ || '').trim();
  if (tz) {
    if (validTimeZone(tz)) return tz;
    logError(`invalid INSURANCE_CLAIM_TZ "${tz}", using JOBS_TZ / default`);
  }
  return jobsTimeZone();
};

// Schemes billed "on demand" are only claimed manually.
const AUTO_FILTER = { autoClaim: { $ne: false }, claimCycle: { $ne: 'on_demand' } };

// Builds the draft claims of one pharmacy. Returns one result row per auto-claim scheme:
//   { schemeId, schemeName, status: 'created' | 'nothing' | 'error', claimId?, claimNumber?, totalAmount?, sales?, error? }
const runPharmacyInsuranceClaims = async (pharmacyId, { now = new Date() } = {}) => {
  const { periodFrom, periodTo, label } = svc.previousMonthRange(now, claimTimeZone());
  const schemes = await InsuranceScheme.find({ pharmacyId, ...AUTO_FILTER }).sort({ name: 1 });
  const results = [];
  for (const scheme of schemes) {
    const row = { schemeId: scheme._id, schemeName: scheme.name };
    const session = await mongoose.startSession();
    try {
      let claim = null;
      await session.withTransaction(async () => {
        claim = await svc.buildClaimForPeriod(
          {
            pharmacyId,
            scheme,
            periodFrom,
            periodTo,
            notes: `Automatic monthly claim for ${label}`,
            autoGenerated: true,
          },
          { session }
        );
        await audit(
          null,
          {
            pharmacyId,
            action: 'insurance.claim_auto_create',
            userName: 'system',
            entity: 'InsuranceClaim',
            entityId: claim._id,
            meta: { claimNumber: claim.claimNumber, totalAmount: claim.totalAmount, sales: claim.sales.length },
          },
          { session }
        );
      });
      results.push({
        ...row,
        status: 'created',
        claimId: claim._id,
        claimNumber: claim.claimNumber,
        totalAmount: claim.totalAmount,
        sales: claim.sales.length,
      });
    } catch (err) {
      if (err && err.code === 'NOTHING_TO_CLAIM') {
        results.push({ ...row, status: 'nothing' });
      } else {
        logError(`pharmacy ${pharmacyId} scheme ${scheme._id}:`, err && err.message);
        results.push({ ...row, status: 'error', error: (err && err.message) || 'error' });
      }
    } finally {
      await session.endSession();
    }
  }
  return results;
};

// All pharmacies (except archived ones) that have at least one auto-claim scheme.
const runInsuranceClaims = async ({ now = new Date() } = {}) => {
  const pharmacyIds = await InsuranceScheme.distinct('pharmacyId', AUTO_FILTER);
  if (pharmacyIds.length === 0) return [];
  const pharmacies = await Pharmacy.find({ _id: { $in: pharmacyIds }, status: { $ne: 'archived' } })
    .select('_id')
    .lean();
  const out = [];
  for (const p of pharmacies) {
    try {
      out.push({ pharmacyId: p._id, schemes: await runPharmacyInsuranceClaims(p._id, { now }) });
    } catch (err) {
      logError(`pharmacy ${p._id}:`, err && err.message);
      out.push({ pharmacyId: p._id, schemes: [], error: (err && err.message) || 'error' });
    }
  }
  return out;
};

module.exports = { runInsuranceClaims, runPharmacyInsuranceClaims, claimTimeZone, DEFAULT_INSURANCE_CLAIM_CRON };
