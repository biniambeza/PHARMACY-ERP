const mongoose = require('mongoose');
const bcrypt = require('bcryptjs');
const { isValidEmail } = require('../utils/email');

const MEMBERSHIP_ROLES = ['owner', 'pharmacist', 'cashier', 'storekeeper'];

const membershipSchema = new mongoose.Schema(
  {
    pharmacyId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'Pharmacy',
      required: true,
    },
    role: {
      type: String,
      enum: {
        values: MEMBERSHIP_ROLES,
        message: '{VALUE} is not a valid staff role',
      },
      required: true,
    },
    active: {
      type: Boolean,
      default: true,
    },
  },
  { _id: false }
);

const userSchema = new mongoose.Schema(
  {
    name: {
      type: String,
      required: [true, 'Please provide a name'],
      trim: true,
    },
    email: {
      type: String,
      required: [true, 'Please provide an email'],
      unique: true,
      lowercase: true,
      trim: true,
      validate: {
        validator: isValidEmail,
        message: 'Please provide a valid email address',
      },
    },
    password: {
      type: String,
      required: [true, 'Please provide a password'],
      minlength: [8, 'Password must be at least 8 characters long'],
    },
    role: {
      type: String,
      enum: {
        values: ['admin', 'pharmacist'],
        message: '{VALUE} is not a valid role. Allowed roles: admin, pharmacist',
      },
      default: 'pharmacist',
    },
    // Included in every JWT (claim `tv`). Incrementing it revokes all tokens
    // issued before, e.g. after a password change.
    tokenVersion: {
      type: Number,
      default: 0,
    },
    // Per-account brute-force protection (controllers/authController.js):
    // failed password / 2FA attempts since the last success; after
    // MAX_FAILED_LOGINS the account is locked until lockUntil.
    failedLoginCount: {
      type: Number,
      default: 0,
      select: false,
    },
    lockUntil: {
      type: Date,
      default: null,
      select: false,
    },
    // Tenant access: one entry per pharmacy (branch) the user works in.
    // Users with role 'pharmacist' and no memberships who own a pharmacy
    // (Pharmacy.owner) are migrated lazily to an 'owner' membership
    // (see utils/membership.js).
    memberships: {
      type: [membershipSchema],
      default: [],
    },
    // Optional organization grouping several branches
    organizationId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'Organization',
      default: null,
    },
    // Two-factor login (TOTP). Only `enabled` / `enabledAt` are ever readable
    // by default; secrets and recovery code hashes are `select: false` and
    // stripped by toJSON/toObject. Load them with
    // .select('+twoFactor.secret +twoFactor.recoveryCodes ...').
    twoFactor: {
      enabled: { type: Boolean, default: false },
      enabledAt: { type: Date, default: null },
      // AES-GCM encrypted base32 secret (utils/twoFactor.js)
      secret: { type: String, select: false, default: null },
      // Secret generated by /2fa/setup, waiting for confirmation by /2fa/enable
      pendingSecret: { type: String, select: false, default: null },
      pendingCreatedAt: { type: Date, select: false, default: null },
      // Last accepted TOTP time step: a code can be used only once
      lastUsedStep: { type: Number, select: false, default: null },
      // Current login challenge (jti of the challenge token) and its failed
      // code attempts; the challenge is invalidated after too many failures.
      challengeId: { type: String, select: false, default: null },
      challengeFailures: { type: Number, select: false, default: 0 },
      recoveryCodes: {
        type: [
          new mongoose.Schema(
            { hash: { type: String, required: true }, usedAt: { type: Date, default: null } },
            { _id: false }
          ),
        ],
        select: false,
        default: undefined,
      },
    },
  },
  {
    timestamps: true,
  }
);

const TWO_FACTOR_PRIVATE = [
  'secret',
  'pendingSecret',
  'pendingCreatedAt',
  'lastUsedStep',
  'recoveryCodes',
  'challengeId',
  'challengeFailures',
];
const stripTwoFactorSecrets = (doc, ret) => {
  if (ret && ret.twoFactor) {
    TWO_FACTOR_PRIVATE.forEach((k) => delete ret.twoFactor[k]);
  }
  if (ret) {
    delete ret.failedLoginCount;
    delete ret.lockUntil;
  }
  return ret;
};
userSchema.set('toJSON', { transform: stripTwoFactorSecrets });

// Hash password before saving to database
userSchema.pre('save', async function () {
  if (!this.isModified('password')) {
    return;
  }
  const salt = await bcrypt.genSalt(10);
  this.password = await bcrypt.hash(this.password, salt);
});

// Helper method to compare entered password with hashed password
userSchema.methods.matchPassword = async function (enteredPassword) {
  return await bcrypt.compare(enteredPassword, this.password);
};

userSchema.index({ 'memberships.pharmacyId': 1 });

const User = mongoose.model('User', userSchema);
User.MEMBERSHIP_ROLES = MEMBERSHIP_ROLES;

module.exports = User;
